import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const axeSource = readFileSync(fileURLToPath(new URL('../../node_modules/axe-core/axe.min.js', import.meta.url)), 'utf8')

async function expectAccessible(page) {
  // Let transient toasts finish their exit animation so axe never measures a
  // half-faded ink surface (which would read as a false contrast failure).
  await expect(page.getByRole('region', { name: 'Notifications' })).toBeEmpty({ timeout: 12000 })
  await page.waitForTimeout(400)
  await page.addScriptTag({ content: axeSource })
  const violations = await page.evaluate(async () => {
    const result = await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] } })
    return result.violations.map((violation) => ({ id: violation.id, targets: violation.nodes.map((node) => node.target) }))
  })
  expect(violations).toEqual([])
}

async function loginStudent(page) {
  await page.addInitScript(() => {
    // Deterministic demo overrides for the mock realtime channel only.
    localStorage.setItem('vyuh.mock.attentionMinSeconds', '2')
    localStorage.setItem('vyuh.mock.attentionMaxSeconds', '4')
    localStorage.setItem('vyuh.mock.approvalDelaySeconds', '2')
    localStorage.setItem('vyuh.mock.chatIntervalSeconds', '3')
    localStorage.setItem('vyuh.mock.presenceTickSeconds', '2')
    localStorage.setItem('vyuh.mock.roomIntervalSeconds', '3')
  })
  await page.goto('/login')
  await page.getByRole('button', { name: 'Quick demo login as Student' }).click()
  await expect(page).toHaveURL(/\/student$/)
}

test('live schedule, attention response, chat/queue realtime and broadcast mode', async ({ page }) => {
  test.setTimeout(60000)
  await loginStudent(page)
  await page.goto('/student/live')
  await expect(page.getByRole('heading', { level: 1, name: 'Live classes' })).toBeVisible()
  await expect(page.getByText('Interactive', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Broadcast', { exact: true }).first()).toBeVisible()
  await page.getByRole('link', { name: 'Join room' }).first().click()
  await expect(page).toHaveURL(/\/student\/live\/ses-rot-b$/)
  await expect(page.getByTestId('live-presence')).toHaveText(/Present, 84%/)
  await expect(page.getByRole('button', { name: 'Unmute microphone' })).toBeVisible()
  const check = page.getByTestId('attention-check')
  await expect(check).toBeVisible({ timeout: 10000 })
  await check.getByRole('button', { name: 'Still here' }).click()
  await expect(page.getByTestId('live-presence')).toHaveText(/Present, 86%/)
  await expect(page.getByRole('log', { name: 'Class chat' })).toContainText('Sir, can we take the axis', { timeout: 10000 })
  await page.getByRole('tab', { name: /Question queue/ }).click()
  await page.getByLabel('Ask the faculty').fill('Can we check the vertical ladder limit?')
  await page.getByRole('button', { name: 'Add to queue' }).click()
  await expect(page.getByRole('list', { name: 'Question queue' }).getByText('Can we check the vertical ladder limit?', { exact: true })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Question queue' }).getByText('Faculty approved').first()).toBeVisible({ timeout: 10000 })
  // Clear the sliding attention toast so the axe scan runs in a quiet window
  // (the next random check is 2–4s away, longer than the scan).
  const stillHere = page.getByTestId('attention-check').getByRole('button', { name: 'Still here' })
  if (await stillHere.count()) await stillHere.click()
  await expectAccessible(page)
  await page.getByRole('button', { name: 'Leave', exact: true }).click()
  await expect(page).toHaveURL(/\/student\/live$/)
  await page.goto('/student/live/ses-rot-b')
  await expect(page.getByRole('button', { name: 'Unmute microphone' })).toBeVisible()
  await expect(page.getByTestId('live-presence')).toContainText('Present')
  await page.goto('/student/live/ses-chem-b')
  await expect(page.getByText('Faculty broadcast · microphone and camera are off for everyone.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Unmute microphone' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Turn camera on' })).toHaveCount(0)
})

test('recording keyboard controls, transcript sync, resume and end-only quiz', async ({ page }) => {
  test.setTimeout(60000)
  await loginStudent(page)
  await page.goto('/student/recordings/rec-int-c')
  const video = page.locator('video')
  const seek = page.getByRole('slider', { name: 'Seek video' })
  await expect(seek).toBeVisible()
  await expect(page.getByTestId('lecture-to-practice')).toHaveCount(0)
  await video.focus()
  await page.keyboard.press('Space')
  await page.waitForFunction(() => document.querySelector('video')?.currentTime > 0.5)
  await page.keyboard.press('ArrowRight')
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThan(5)
  await page.getByRole('button', { name: 'Pause video' }).click()
  await page.getByRole('tab', { name: 'Transcript' }).click()
  await page.getByRole('button', { name: /2\. Change the limits/ }).click()
  await expect.poll(async () => Number(await seek.inputValue())).toBeGreaterThanOrEqual(12)
  const activeLine = page.getByRole('list', { name: 'Transcript' }).locator('button[aria-current="true"]')
  await expect(activeLine).toContainText('When you substitute')
  await page.getByLabel('Search transcript').fill('limits')
  await expect(page.getByRole('list', { name: 'Transcript' })).toContainText('change the limits immediately')
  await page.getByLabel('Search transcript').fill('')
  await page.getByRole('button', { name: 'Play video' }).click()
  await page.waitForFunction(() => document.querySelector('video')?.currentTime > 13)
  await page.getByRole('button', { name: 'Pause video' }).click()
  await expect(page.getByText('Resume saved')).toBeVisible({ timeout: 10000 })
  const saved = Number(await seek.inputValue())
  await page.reload()
  await expect.poll(async () => Number(await page.getByRole('slider', { name: 'Seek video' }).inputValue())).toBeGreaterThanOrEqual(saved - 0.5)
  await expect(page.getByTestId('lecture-to-practice')).toHaveCount(0)
  const seekAfterReload = page.getByRole('slider', { name: 'Seek video' })
  await seekAfterReload.focus()
  await page.keyboard.press('End')
  for (let i = 0; i < 5; i += 1) await page.keyboard.press('ArrowLeft')
  await expect.poll(async () => Number(await seekAfterReload.inputValue())).toBeGreaterThan(47)
  await page.getByRole('button', { name: 'Play video' }).focus()
  await page.keyboard.press('Space')
  await expect(page.getByTestId('lecture-to-practice')).toBeVisible({ timeout: 10000 })
  await page.getByRole('radio', { name: /B\. They swap and the sign changes/ }).check()
  await page.getByRole('radio', { name: /B\. Zero/ }).check()
  await page.getByRole('radio', { name: /B\. a \+ b − x/ }).check()
  await page.getByRole('button', { name: 'Check my understanding' }).click()
  await expect(page.getByText('You scored')).toContainText('3/3')
  await expectAccessible(page)
})

